export type Task = keyof typeof tasks;
export type Group = keyof typeof fieldGroups;
type Weather = "clear" | "rain" | "fog" | "dusk" | "snow" | "ice";
export type FieldDrive = {
  id: string;
  group: Group;
  name: ReturnType<typeof tr>;
  weather: Weather;
  bend: number;
  stages: readonly [Task, Task, Task];
};
function route(
  id: string,
  group: Group,
  en: string,
  zh: string,
  ja: string,
  weather: Weather,
  bend: number,
  ...stages: [Task, Task, Task]
): FieldDrive {
  return {
    id: "field-" + id,
    group,
    name: tr(en, zh, ja),
    weather,
    bend,
    stages,
  };
}
